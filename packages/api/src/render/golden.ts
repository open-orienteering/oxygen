/**
 * Golden PNGs for the WebGL2 screenshot tests: the reference raster of
 * each golden scene at the fixed golden density, encoded as PNG — and the
 * symbol library's contact sheet, one swatch per entry. Shared by the
 * generator script (`scripts/render-golden.ts`) and the tests that keep
 * the committed files in sync with the oracle.
 */

import { render, symbolLibrary } from "@oxygen/shared";
import { loadBundledFont, glyphOutlineFrom } from "./fonts.js";
import { renderSwatchPng, stackColour } from "./previews.js";
import { encodePng, rasterisePassStream } from "./reference-raster.js";

/**
 * Goldens are rendered at this multiple of the golden density and box-
 * filtered down: resvg flattens curves to ~¼ px chords and the extra
 * density shrinks that error (and edge-coverage rounding) below the
 * per-channel tolerance, so the comparison measures the backend, not
 * the oracle's rasteriser.
 */
export const GOLDEN_SUPERSAMPLE = 4;

/** `e2e/__golden__/map-gl/` — Playwright's `snapshotPathTemplate` points here. */
export const goldenDir = new URL("../../../../e2e/__golden__/map-gl/", import.meta.url);

export async function goldenFonts(): Promise<render.TrueTypeFont[]> {
  return Promise.all([loadBundledFont("liberation-sans"), loadBundledFont("liberation-sans-narrow")]);
}

export async function renderGoldenPng(name: render.GoldenSceneName): Promise<Buffer> {
  const fonts = await goldenFonts();
  const scene = render.goldenScene(name, fonts);
  const { bounds } = render.goldenFrame(scene.stream);
  const img = await rasterisePassStream(scene.stream, {
    colour: scene.colour,
    bounds,
    pxPerMm: render.GOLDEN_PX_PER_MM,
    glyphOutline: glyphOutlineFrom(fonts),
    supersample: GOLDEN_SUPERSAMPLE,
  });
  return encodePng(img);
}

// ---- library contact sheet (docs/map-symbols.md §6 (d)) ---------------------

/** `e2e/__golden__/library/` — one directory of swatches per library, plus `<libraryId>.md`. */
export const libraryGoldenDir = new URL("../../../../e2e/__golden__/library/", import.meta.url);

export const LIBRARY_GOLDEN_IDS: readonly symbolLibrary.SymbolLibraryId[] = ["ISOM2017-2", "ISSprOM2019-2"];

/** `302.b.png` for `ISOM2017-2:302.b`: the entry id after the library prefix. */
export function libraryGoldenFile(entry: Pick<symbolLibrary.LibraryEntry, "id">): string {
  return `${entry.id.slice(entry.id.indexOf(":") + 1)}.png`;
}

export interface LibraryGolden {
  entryId: string;
  file: string;
  png: Buffer;
}

/**
 * Every entry of the library as its swatch PNG — exactly what the library
 * preview route serves (`map-storage.md` §4.5): the swatch scene at 10 px/mm
 * against the library's own palette stack, not supersampled.
 */
export async function renderLibraryGoldens(id: symbolLibrary.SymbolLibraryId): Promise<LibraryGolden[]> {
  const { library, colours, symbols } = symbolLibrary.materialiseLibrary(id);
  const colour = stackColour(colours);
  const out: LibraryGolden[] = [];
  for (let i = 0; i < library.entries.length; i++) {
    const entry = library.entries[i];
    out.push({ entryId: entry.id, file: libraryGoldenFile(entry), png: await renderSwatchPng(symbols[i], colour) });
  }
  return out;
}

const cell = (s: string) => s.replace(/\|/g, "\\|");

/** The index page committed beside the swatches: one table row per entry, in library order. */
export function librarySheetMarkdown(id: symbolLibrary.SymbolLibraryId): string {
  const library = symbolLibrary.getSymbolLibrary(id);
  const lines = [
    `# ${library.id} contact sheet`,
    "",
    `<!-- Generated by \`pnpm --filter @oxygen/api golden:render\` — do not edit. Spec: docs/map-symbols.md §6 (d). -->`,
    "",
    `${library.entries.length} entries, ${library.revision}, library version ${symbolLibrary.SYMBOL_LIBRARY_VERSION}. Swatches at ${render.SWATCH.pxPerMm} px/mm; points drawn ×${render.SWATCH.pointScale}.`,
    "",
    `Svenska: ${symbolLibrary.symbolLibraryNameSources[id].sv}. Aliases: ${symbolLibrary.symbolLibraryNameSources[id].aliases ?? "none yet"}.`,
    "",
    "| Swatch | Entry | Type | English | Svenska | Aliases |",
    "|---|---|---|---|---|---|",
  ];
  for (const e of library.entries) {
    const file = libraryGoldenFile(e);
    const aliases = e.aliases.map((a) => `${a.library} ${a.code}`).join(", ");
    lines.push(`| ![${e.id}](${library.id}/${file}) | \`${e.id.slice(e.id.indexOf(":") + 1)}\` | ${e.specType} | ${cell(e.name.en)} | ${cell(e.name.sv ?? "—")} | ${aliases || "—"} |`);
  }
  return `${lines.join("\n")}\n`;
}
