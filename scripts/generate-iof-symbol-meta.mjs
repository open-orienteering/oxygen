#!/usr/bin/env node
// Generates packages/shared/src/course-maps/iof-symbol-meta.ts from the
// svg-control-descriptions package's lang.json (names extracted from
// Purple Pen's symbols.xml). Emits every kind used by the control
// description sheet / editor (A, C–H, special-instruction letters),
// filtered to symbols that actually exist in iof-symbols.ts, and only
// the languages Oxygen ships (en, sv).
//
// Usage: node scripts/generate-iof-symbol-meta.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const langPath = join(root, "node_modules/svg-control-descriptions/symbols/lang.json");
const symbolsPath = join(root, "packages/shared/src/course-maps/iof-symbols.ts");
const outPath = join(root, "packages/shared/src/course-maps/iof-symbol-meta.ts");

const lang = JSON.parse(readFileSync(langPath, "utf8"));

// Keys present in the generated SVG module.
const symbolsSource = readFileSync(symbolsPath, "utf8");
const availableKeys = new Set(
  [...symbolsSource.matchAll(/^ {2}"([^"]+)":/gm)].map((m) => m[1]),
);

/** Sheet / editor kinds we surface (includes special-instruction rows). */
const KINDS = new Set(["A", "C", "D", "E", "F", "G", "H", "W", "X", "Y", "Z", "V"]);

// Purple Pen's lang.json lacks Swedish names for a few IOF 2018 symbols.
const SV_FALLBACKS = {
  "2.10": "Skyttegrav",
  "5.25": "Rabatt / förbjudet område",
  "5.26": "Järnväg",
  "15.6": "Kartvändning",
};

const KIND_UNION = [...KINDS].map((k) => JSON.stringify(k)).join(" | ");

const entries = [];
for (const [key, info] of Object.entries(lang)) {
  if (!KINDS.has(info.kind)) continue;
  if (!availableKeys.has(key)) continue;
  const en = info.names?.en;
  const sv = info.names?.sv ?? SV_FALLBACKS[key];
  if (!en || !sv) throw new Error(`Missing en/sv name for symbol ${key}`);
  entries.push({ key, kind: info.kind, en, sv });
}

entries.sort((a, b) => a.key.localeCompare(b.key, "en", { numeric: true }));

const lines = entries.map(
  (e) =>
    `  ${JSON.stringify(e.key)}: { kind: ${JSON.stringify(e.kind)}, en: ${JSON.stringify(e.en)}, sv: ${JSON.stringify(e.sv)} },`,
);

const out = `// Auto-generated by scripts/generate-iof-symbol-meta.mjs. Do not edit manually.
// IOF control description symbol metadata (sheet column + names) from the
// svg-control-descriptions package (extracted from Purple Pen).

export interface IofSymbolMeta {
  /** Description sheet column / row kind. */
  kind: ${KIND_UNION};
  en: string;
  sv: string;
}

export const IOF_SYMBOL_META: Record<string, IofSymbolMeta> = {
${lines.join("\n")}
};

/** Localized symbol name; falls back to English for unknown languages. */
export function iofSymbolName(iofKey: string, language: string): string {
  const meta = IOF_SYMBOL_META[iofKey];
  if (!meta) return iofKey;
  return language.startsWith("sv") ? meta.sv : meta.en;
}
`;

writeFileSync(outPath, out);
console.log(`Wrote ${entries.length} symbols to ${outPath}`);
